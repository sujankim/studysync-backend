// The 5 types of resources users can share in a room
public enum ResourceType {
    PDF,       // PDF documents
    IMAGE,     // PNG, JPG, GIF etc.
    VIDEO,     // MP4, MOV etc.
    LINK,      // Any URL — no file upload needed
    DOCUMENT   // Word docs, Excel, PowerPoint etc.
}
